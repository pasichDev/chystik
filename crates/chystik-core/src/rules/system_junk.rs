fn home_rule(dir: &Path) -> Option<Match> {
    let home = home_root()?;
    let rel = dir
        .strip_prefix(&home)
        .ok()?
        .to_string_lossy()
        .replace('\\', "/");
    let (_, sev, note) = *HOME_TARGETS.iter().find(|(s, ..)| rel == *s)?;
    Some(Match {
        category: Category::SystemJunk,
        severity: sev,
        note: note.into(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    fn mk(root: &std::path::Path, rel: &str) -> std::path::PathBuf {
        std::fs::create_dir_all(root.join(rel)).unwrap();
        root.join(rel)
    }

    use crate::rules::TEST_ENV_LOCK as ENV_LOCK;

    #[test]
    fn shader_font_and_index_caches_match_with_expected_severity() {
        let _env = ENV_LOCK.lock().unwrap_or_else(|p| p.into_inner());
        let fake = tempdir().unwrap();
        std::env::set_var("CHYSTIK_TEST_HOME", fake.path());
        for rel in [
            ".cache/mesa_shader_cache",
            ".cache/mesa_shader_cache_db",
            ".cache/nvidia/GLCache",
            ".cache/qtshadercache",
            ".cache/fontconfig",
            ".cache/gnome-shell",
            ".cache/icon-cache.kcache",
            ".cache/tracker3",
            ".local/share/drkonqi/crashes",
        ] {
            let m = classify(&mk(fake.path(), rel)).expect(rel);
            assert_eq!(m.category, Category::SystemJunk, "{rel}");
            assert_eq!(m.severity, Severity::Safe, "{rel}");
        }
        let baloo = classify(&mk(fake.path(), ".local/share/baloo")).expect("baloo");
        assert_eq!(baloo.severity, Severity::Moderate);
        let tracker = classify(&mk(fake.path(), ".local/share/tracker3")).expect("tracker");
        assert_eq!(tracker.severity, Severity::Moderate);
        // Negatives: bare .cache, thumbnails (core.rs owns it), typos.
        assert!(classify(&mk(fake.path(), ".cache")).is_none());
        assert!(classify(&mk(fake.path(), ".cache/thumbnails")).is_none());
        assert!(classify(&mk(fake.path(), ".local/share/baloo4")).is_none());
        assert!(classify(&mk(fake.path(), "fontconfig")).is_none());
        std::env::remove_var("CHYSTIK_TEST_HOME");
    }

    #[test]
    fn correctly_named_tree_outside_home_does_not_match() {
        let root = tempdir().unwrap();
        assert!(classify(&mk(root.path(), "x/.cache/fontconfig")).is_none());
    }
}
