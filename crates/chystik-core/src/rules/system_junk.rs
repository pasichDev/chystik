//! Generic system junk in `$HOME`: app crash dumps, stale core files,
//! orphaned X11/Wayland session leftovers, one-off `.cache` strays.

use std::path::Path;

use crate::model::{Category, Severity};

use super::{home_root, Match};

/// Evaluate the system-junk rule set against `dir`.
pub(crate) fn classify(dir: &Path) -> Option<Match> {
    home_rule(dir)
}
